"""Field audit from two raw GH Archive hourly files (no BigQuery).

Input:  data/raw/gharchive/2025-09-15-12.json (pre-change), 2025-11-15-12.json (post-change)
Output: reports/field_audit.md            field diff per event type + answers to the audit questions
        reports/field_audit_paths.csv     every payload path with presence counts
        data/samples/field_audit/<hour>/<type>.json   3 raw payloads per type (git-ignored)

Run: .venv/bin/python scripts/01_field_audit_files.py
"""
from __future__ import annotations

import json
from collections import Counter, defaultdict

from codebeat.config import REPO_ROOT

RAW = REPO_ROOT / "data/raw/gharchive"
HOURS = {"pre": "2025-09-15-12", "post": "2025-11-15-12"}
TYPES = ["PushEvent", "PullRequestEvent", "PullRequestEvent:closed", "PullRequestReviewEvent",
         "PullRequestReviewCommentEvent", "IssuesEvent", "IssueCommentEvent"]
AA_TYPES = TYPES[1:]  # PR / issue / comment events checked for author_association
N_SAMPLES = 3


def flatten(obj, prefix=""):
    """Yield (path, value) for nested dicts; lists are leaves (path gets [] suffix)."""
    for k, v in obj.items():
        p = f"{prefix}.{k}" if prefix else k
        if isinstance(v, dict):
            yield p, v
            yield from flatten(v, p)
        else:
            yield (p + "[]" if isinstance(v, list) else p), v


def scan(hour: str):
    n = Counter()
    present = defaultdict(Counter)   # group -> path -> rows where key exists
    nonnull = defaultdict(Counter)   # group -> path -> rows where value is non-null and non-empty
    samples = defaultdict(list)
    with open(RAW / f"{hour}.json") as f:
        for line in f:
            ev = json.loads(line)
            t = ev["type"]
            if t not in TYPES:
                continue
            p = ev.get("payload") or {}
            groups = [t] + (["PullRequestEvent:closed"]
                            if t == "PullRequestEvent" and p.get("action") == "closed" else [])
            for g in groups:
                n[g] += 1
                for path, val in flatten(p):
                    present[g][path] += 1
                    if val not in (None, "", [], {}):
                        nonnull[g][path] += 1
            if len(samples[t]) < N_SAMPLES:
                samples[t].append(p)
    out = REPO_ROOT / "data/samples/field_audit" / hour
    out.mkdir(parents=True, exist_ok=True)
    for t, s in samples.items():
        (out / f"{t}.json").write_text(json.dumps(s, indent=2))
    return n, present, nonnull


def pct(num, den):
    return f"{100 * num / den:.0f}%" if den else "n/a"


def main():
    res = {k: scan(h) for k, h in HOURS.items()}
    (npre, ppre, nnpre), (npost, ppost, nnpost) = res["pre"], res["post"]

    csv = ["group,path,pre_present,pre_nonnull,pre_n,post_present,post_nonnull,post_n"]
    for g in TYPES:
        for path in sorted(set(ppre[g]) | set(ppost[g])):
            csv.append(f"{g},{path},{ppre[g][path]},{nnpre[g][path]},{npre[g]},"
                       f"{ppost[g][path]},{nnpost[g][path]},{npost[g]}")
    (REPO_ROOT / "reports/field_audit_paths.csv").write_text("\n".join(csv) + "\n")

    def row(g, path):
        return (f"| `{path}` | {pct(nnpre[g][path], npre[g])} / {pct(ppre[g][path], npre[g])} "
                f"| {pct(nnpost[g][path], npost[g])} / {pct(ppost[g][path], npost[g])} |")

    md = ["# GH Archive field audit (raw hourly files)", "",
          f"Generated by `scripts/01_field_audit_files.py` from `{HOURS['pre']}` (pre-change) and "
          f"`{HOURS['post']}` (post-change). No BigQuery used.", "",
          "Cells: `% rows non-null / % rows where the key exists`. Payload paths only; lists shown as `[]`.", "",
          "| Group | Pre rows | Post rows |", "|---|---|---|"]
    md += [f"| {g} | {npre[g]:,} | {npost[g]:,} |" for g in TYPES]

    # Q1 PushEvent commits
    md += ["", "## Q1. PushEvent commit lists and counts", "",
           "| Field | Pre | Post |", "|---|---|---|"]
    md += [row("PushEvent", p) for p in ["size", "distinct_size", "commits[]", "ref", "head", "before",
                                          "push_id", "repository_id"]]
    # Q2 author_association
    md += ["", "## Q2. author_association in PR / issue / comment events", "",
           "| Group | Path | Pre | Post |", "|---|---|---|---|"]
    for g in AA_TYPES:
        paths = sorted(p for p in set(ppre[g]) | set(ppost[g]) if p.endswith("author_association"))
        for p in paths or ["(none found)"]:
            md.append(f"| {g} | `{p}` | {pct(nnpre[g][p], npre[g])} / {pct(ppre[g][p], npre[g])} "
                      f"| {pct(nnpost[g][p], npost[g])} / {pct(ppost[g][p], npost[g])} |")
    # Merged status on closed PRs (needed by the label)
    md += ["", "## Merged status on closed PRs", "", "| Field | Pre | Post |", "|---|---|---|"]
    md += [row("PullRequestEvent:closed", p) for p in
           ["pull_request.merged", "pull_request.merged_at", "pull_request.merged_by",
            "pull_request.closed_at", "pull_request.merge_commit_sha", "pull_request.user.login"]]

    # Full diff
    md += ["", "## Field diff per event type", ""]
    for g in TYPES:
        gone = sorted(set(ppre[g]) - set(ppost[g]))
        new = sorted(set(ppost[g]) - set(ppre[g]))
        top = lambda paths: sorted({p.split(".")[0] if p.count(".") > 1 else p for p in paths})
        md += [f"### {g}", "",
               f"- Paths in pre: {len(ppre[g])}, in post: {len(ppost[g])}, removed: {len(gone)}, added: {len(new)}",
               f"- Kept in post: {', '.join(f'`{p}`' for p in sorted(ppost[g]))}" if ppost[g] else "- Kept: none",
               f"- Removed (collapsed to depth 2): {', '.join(f'`{p}`' for p in top(gone)) or 'none'}",
               f"- Added: {', '.join(f'`{p}`' for p in new) or 'none'}", ""]
    md += ["## Interpretation", "", "_Written after review._", ""]
    (REPO_ROOT / "reports/field_audit.md").write_text("\n".join(md))
    print("\n".join(md[:60]))


if __name__ == "__main__":
    main()
